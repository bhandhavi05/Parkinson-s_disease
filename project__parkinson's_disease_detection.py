import gradio as gr
import pickle
import numpy as np

# Load model and scaler
model = pickle.load(open("parkinson_model.pkl", "rb"))
scaler = pickle.load(open("scaler.pkl", "rb"))

# 22 features
feature_names = [
"MDVP:Fo(Hz)", "MDVP:Fhi(Hz)", "MDVP:Flo(Hz)", "MDVP:Jitter(%)",
"MDVP:Jitter(Abs)", "MDVP:RAP", "MDVP:PPQ", "Jitter:DDP", "MDVP:Shimmer",
"MDVP:Shimmer(dB)", "Shimmer:APQ3", "Shimmer:APQ5", "MDVP:APQ",
"Shimmer:DDA", "NHR", "HNR", "RPDE", "DFA",
"spread1", "spread2", "D2", "PPE"
]

def predict(*values):
    scaled = scaler.transform([values])
    prediction = model.predict(scaled)[0]
    proba = model.predict_proba(scaled)[0][1]

    if prediction == 1:
        result = f"🔴 Parkinson's Detected (Confidence: {proba:.2f})"
    else:
        result = f"🟢 No Parkinson's Detected (Confidence: {1-proba:.2f})"

    return result

inputs = [gr.Number(label=name) for name in feature_names]
output = gr.Textbox(label="Prediction Result")

gr.Interface(fn=predict, inputs=inputs, outputs=output, title="Parkinson’s Disease Detection").launch()